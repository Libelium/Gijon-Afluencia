"""
Publishes the prediction CSVs (already generated by PredictTransform) via
storage + importation queue - the SAME mechanism as etl/crowd/load.py, with no
changes (helpers/uploader.py is already generic over any directory of entity
CSVs).
"""

import logging

from crowd_predictions.helpers.uploader import upload_csv_files

logger = logging.getLogger(__name__)

class PredictLoad:
    def __init__(self, csv_files: list):
        # The files THIS run produced, not whatever is in the directory: the output
        # directory is never cleaned, so a glob republishes previous runs.
        self.csv_files = csv_files

    def load(self) -> bool:
        if not self.csv_files:
            logger.error("Nothing was generated to publish.")
            return False
        results = upload_csv_files(self.csv_files)
        return len(results["successful"]) > 0 and len(results["failed"]) == 0
